/**
 * Builds the herdr-app mods in herdr-mods/: each mod's `lib.entry.ts` (the web client's pure chat
 * helpers it reuses) is bundled into the mod's `lib.js`, an ES module QuickJS can load. The mod runs
 * without a DOM or React, so the UI-text module is swapped for English `t` (the mod has no language
 * setting yet) and a helper that pulls in anything else fails the build's size check rather than
 * shipping React to the mod.
 *
 *   bun scripts/build-herdr-mods.ts
 */
import { existsSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const ROOT = join(import.meta.dir, "..");
export const MODS_DIR = join(ROOT, "herdr-mods");
/** A bundle past this pulled in more than pure helpers (React alone is 500 KB). */
const MAX_LIB_BYTES = 200_000;

const englishI18n = `export function t(key, vars) {
  return vars === undefined ? key : key.replace(/\\{(\\w+)\\}/g, (match, name) => (name in vars ? String(vars[name]) : match));
}
export const translate = (_language, key, vars) => t(key, vars);
export function currentLocale() { return "en-US"; }`;

/** The mods that have something to build: a folder with a `lib.entry.ts`. */
export function modsWithLib(): string[] {
  return readdirSync(MODS_DIR).filter((name) => existsSync(join(MODS_DIR, name, "lib.entry.ts")));
}

export async function buildHerdrMods(): Promise<string[]> {
  const built: string[] = [];
  for (const name of modsWithLib()) {
    const dir = join(MODS_DIR, name);
    const result = await Bun.build({
      entrypoints: [join(dir, "lib.entry.ts")],
      format: "esm",
      target: "browser",
      plugins: [{
        name: "english-i18n",
        setup(build) {
          build.onLoad({ filter: /src\/lib\/i18n\.ts$/ }, () => ({ contents: englishI18n, loader: "js" }));
        },
      }],
    });
    if (!result.success) throw new AggregateError(result.logs, `herdr-mods/${name}: build failed`);
    const out = join(dir, "lib.js");
    await Bun.write(out, `// Generated by scripts/build-herdr-mods.ts from lib.entry.ts: do not edit.\n${await result.outputs[0]!.text()}`);
    if (statSync(out).size > MAX_LIB_BYTES) throw new Error(`herdr-mods/${name}/lib.js is ${statSync(out).size} bytes: a helper pulled in more than pure logic`);
    built.push(out);
  }
  return built;
}

if (import.meta.main) {
  for (const out of await buildHerdrMods()) console.log(out);
}
